class TestCsrfProtection:
    """Unit tests for CSRFProtection token generation and validation."""

    def _config(self) -> CSRFConfig:
        return CSRFConfig(enabled=True, _secret_key="test-secret-key-32bytes-long!!")

    def test_generate_token_returns_hex_string(self) -> None:
        """generate_token returns a non-empty hex string."""
        csrf = CSRFProtection(config=self._config())
        token = csrf.generate_token(session_id="user-123")
        assert isinstance(token, str)
        assert len(token) > 0
        # Must be valid hex
        int(token, 16)

    def test_generate_token_raises_without_secret_key(self) -> None:
        """generate_token raises ValueError when secret_key is not configured."""
        csrf = CSRFProtection(config=CSRFConfig(enabled=True))
        with pytest.raises(ValueError, match="secret_key must be set"):
            csrf.generate_token(session_id="user-123")

    def test_validate_token_accepts_valid_token(self) -> None:
        """validate_token returns True for a token generated by generate_token."""
        csrf = CSRFProtection(config=self._config())
        token = csrf.generate_token(session_id="user-123")
        assert csrf.validate_token(token, session_id="user-123") is True

    def test_validate_token_rejects_wrong_session(self) -> None:
        """validate_token returns False when the session_id doesn't match."""
        csrf = CSRFProtection(config=self._config())
        token = csrf.generate_token(session_id="user-123")
        assert csrf.validate_token(token, session_id="other-user") is False

    def test_validate_token_rejects_empty_inputs(self) -> None:
        """validate_token returns False for empty token or session_id."""
        csrf = CSRFProtection(config=self._config())
        assert csrf.validate_token("", session_id="user-123") is False
        assert csrf.validate_token("sometoken", session_id="") is False

    def test_validate_token_rejects_malformed_token(self) -> None:
        """validate_token returns False for a token with wrong length."""
        csrf = CSRFProtection(config=self._config())
        assert csrf.validate_token("tooshort", session_id="user-123") is False

    def test_validate_token_raises_without_secret_key(self) -> None:
        """validate_token raises ValueError when secret_key is not configured."""
        csrf = CSRFProtection(config=CSRFConfig(enabled=True))
        with pytest.raises(ValueError, match="secret_key must be set"):
            csrf.validate_token("sometoken", session_id="user-123")

    def test_config_property(self) -> None:
        """config property returns the CSRFConfig passed at construction."""
        config = self._config()
        csrf = CSRFProtection(config=config)
        assert csrf.config is config


class TestCsrfMiddlewareWiringEnabled:
    """Integration: CSRFProtectionMiddleware is wired when csrf.enabled = True."""

    @pytest.mark.asyncio
    async def test_csrf_middleware_present_when_enabled(self, test_bed) -> None:
        """When csrf.enabled = True, CSRFProtectionMiddleware is added to the stack."""
        from unittest.mock import MagicMock


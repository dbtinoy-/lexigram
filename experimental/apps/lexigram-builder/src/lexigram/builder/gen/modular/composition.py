"""The composition root (G4).

`app.py` is where infrastructure, the bounded contexts and the web surface
get assembled, and it is what the ASGI target points at:

    application.add_modules([
        *infrastructure_modules(),
        *MODULES,
        WebModule.configure(discover=["<pkg>.controllers", "<pkg>.modules"]),
    ])

Controllers are **discovered**, not registered — in both roots, because a
controller that has not joined a module lives at the app root and one that
has lives inside it. Listing them explicitly quietly breaks module
boundaries: a controller would then be wired by the composition root rather
than by the module that owns it.

As with the module scaffold (G1), this does not reimplement upstream's
template. It builds the `ProjectTemplateSpec` the CLI's own `_app_py`
expects and calls it, so a canvas-built composition root is the same file
`lexigram new` writes. The only thing derived here is *which features the
graph implies*, which is the one thing the CLI cannot know.
"""

from __future__ import annotations

from lexigram.builder.graph.models import GraphDocument
from lexigram.builder.graph.modules import derive_modules
from lexigram.cli.scaffold import (  # noqa: PLC2701 -- see module docstring
    ProjectTemplateSpec,
    _app_py,
)

#: Capability ids from ``derive_modules`` that the composition root reacts
#: to. ``_app_py`` branches on ``web`` and ``graphql``; ``sql`` rides along
#: because templates carry it and it keeps the spec honest.
COMPOSITION_FEATURES: frozenset[str] = frozenset({"web", "graphql", "sql"})


def feature_set(document: GraphDocument) -> frozenset[str]:
    """Features the graph implies, in the CLI's own vocabulary.

    ``derive_modules`` already decides which capabilities a graph turns on
    and uses the same ids the templates do, so the mapping is an
    intersection rather than a translation table -- nothing to keep in sync.
    """
    enabled = {card.id for card in derive_modules(document) if card.on}
    return frozenset(enabled & COMPOSITION_FEATURES)


def emit_app(
    document: GraphDocument, *, project_name: str, app_package: str
) -> str:
    """Return ``src/<pkg>/app.py`` for the modular structure."""
    spec = ProjectTemplateSpec(
        name=project_name,
        description=f"{project_name} - generated by lexigram-builder.",
        dependencies=(),
        features=feature_set(document),
        notes=(),
    )
    return _app_py(project_name, app_package, spec)


def asgi_target(app_module: str) -> str:
    """The ``[tool.lexigram] module`` value: always the composition root.

    ``app.py`` is where infrastructure, the bounded contexts and the web
    surface are assembled, and it exposes a module-level ``app``. It used to
    branch — non-modular projects booted ``main:app`` — and the branch was
    the difference between a project starting and a project 404ing on every
    route, which is reason enough not to have one.
    """
    return f"{app_module}.app:app"

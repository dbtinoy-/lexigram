"""Emitters for the ``file_upload`` node kind (nodes plan N3.3).

Two artifacts per route-wired upload config:

* ``src/app/uploads/<name>_upload_storage.py`` — a ``<Pascal>UploadStorage``
  service: local-disk v1. Runs the framework's ``FileUploadPipeline``
  (``FileSizeValidator`` + MIME/extension validators derived from the node's
  ``allowed_types``) and saves accepted files under ``directory`` with
  generated names (``FileUpload.save_to`` keeps writes inside the base dir).
* ``src/app/controllers/<name>_upload_controller.py`` — a
  ``POST <route>/upload`` endpoint that parses the multipart form (``file``
  field), runs it through the storage service and returns file metadata.

Honesty notes (mirroring the search-index emitter):

* ``storage`` values ``s3`` / ``gcs`` / ``azure_blob`` are not backend-backed
  yet — they fall back to local disk with a note in the emitted module.
* ``generate_thumbnails`` / ``thumbnail_sizes`` are reserved knobs with no
  emission effect in v1 (documented in the emitted docstrings).
"""

from __future__ import annotations

import re

from lexigram.builder.gen.emitters.context import pascal_entity
from lexigram.builder.gen.layout import DEFAULT_LAYOUT
from lexigram.builder.graph.models import FileUploadConfig

_EXTERNAL_STORAGE: frozenset[str] = frozenset({"s3", "gcs", "azure_blob"})

_HEADER = "# Generated by lexigram-builder. Do not edit; regenerate instead.\n"

_MAX_SIZE_RE = re.compile(r"^(\d+(?:\.\d+)?)\s?(kb|mb|gb)$", re.IGNORECASE)
_UNIT_BYTES = {"kb": 1024, "mb": 1024**2, "gb": 1024**3}


def effective_storage(config: FileUploadConfig) -> str:
    """Resolve the storage backend actually emitted for this upload config.

    ``local`` is emitted natively. External backends (``s3`` / ``gcs`` /
    ``azure_blob``) are not backend-backed yet and fall back to ``local``;
    the fallback is documented in the emitted storage module.
    """
    if config.storage in _EXTERNAL_STORAGE:
        return "local"
    return config.storage


def _split_allowed_types(
    allowed_types: tuple[str, ...],
) -> tuple[list[str], list[str], list[str]]:
    """Split allowed types into (exact mimes, wildcard prefixes, extensions)."""
    mimes: list[str] = []
    wildcards: list[str] = []
    extensions: list[str] = []
    for allowed in allowed_types:
        lowered = allowed.lower()
        if lowered.startswith("."):
            extensions.append(lowered)
        elif "*" in lowered:
            wildcards.append(lowered.removesuffix("*"))
        elif "/" in lowered:
            mimes.append(lowered)
        else:
            # Validation rejects bare words; keep them out of the emitted gate.
            continue
    return mimes, wildcards, extensions


def parse_max_size_bytes(max_size: str) -> int:
    """``"5MB"`` -> bytes (also used by tests as the spec for the emitted helper)."""
    match = _MAX_SIZE_RE.match(max_size.strip())
    if not match:
        return 5 * 1024**2
    value = float(match.group(1))
    return int(value * _UNIT_BYTES[match.group(2).lower()])


def emit_upload_storage(entity_name: str, config: FileUploadConfig) -> str:
    """Render ``src/app/uploads/<name>_upload_storage.py``."""
    pascal = pascal_entity(entity_name)
    directory = config.directory.strip() or "uploads"
    max_bytes = parse_max_size_bytes(config.max_size)
    mimes, wildcards, extensions = _split_allowed_types(config.allowed_types)
    external = config.storage in _EXTERNAL_STORAGE

    notes: list[str] = []
    if external:
        notes.append("")
        notes.append(
            f"NOTE: storage {config.storage!r} is not backend-backed yet --"
            " files are stored on the local disk instead. Swap in a real"
            " backend here when you outgrow local storage."
        )
    if config.generate_thumbnails:
        notes.append("")
        notes.append(
            "NOTE: generate_thumbnails / thumbnail_sizes are reserved knobs"
            " in this version -- only originals are stored."
        )

    # --- validator imports + pipeline construction -------------------------
    # MIME entries, wildcards and extensions are alternatives: a file is
    # accepted when its extension OR its content type (exact or prefix) is
    # allowed. One emitted gate class handles all three shapes.
    imports = [
        "from lexigram.result import Err, Ok, Result",
        "from lexigram.web.uploads import (",
        "    FileSizeValidator,",
        "    FileTypeValidator,",
        "    FileUpload,",
        "    FileUploadPipeline,",
        "    FileValidationError,",
        ")",
    ]

    validators: list[str] = [f"FileSizeValidator(max_size_bytes={max_bytes!r})"]
    if mimes or wildcards or extensions:
        validators.append(
            f"_UploadTypeGate({(mimes, wildcards, extensions)!r})"
        )
    validators_src = ",\n            ".join(validators)

    gate_class: list[str] = []
    if mimes or wildcards or extensions:
        gate_class = [
            "class _UploadTypeGate(FileTypeValidator):",
            '    """Accept when the extension OR the content type is allowed.',
            "",
            "    MIME entries match exactly, wildcard entries (``image/*``) by",
            "    prefix, extensions by filename suffix.",
            '    """',
            "",
            "    def __init__(",
            "        self,",
            "        allowed: tuple[list[str], list[str], list[str]],",
            "    ) -> None:",
            "        mimes, wildcards, extensions = allowed",
            "        super().__init__(mimes)",
            "        self._prefixes = tuple(dict.fromkeys(wildcards))",
            "        self._extensions = tuple(dict.fromkeys(extensions))",
            "",
            "    async def validate(self, upload: FileUpload):",
            "        if self._extensions and upload.extension in self._extensions:",
            "            return Ok(None)",
            "        base = await super().validate(upload)",
            "        if base.is_ok():",
            "            return base",
            "        lower = upload.content_type.lower()",
            "        if any(",
            "            lower.startswith(prefix) for prefix in self._prefixes",
            "        ):",
            "            return Ok(None)",
            "        return base",
            "",
            "",
        ]

    lines: list[str] = [
        _HEADER,
        f'"""{pascal} upload storage (file-upload node).',
        "",
        "Local-disk storage guarded by the framework's upload pipeline",
        "(size + MIME/extension validators). Saved names are generated, and",
        "FileUpload.save_to keeps writes inside the base directory.",
        *notes,
        '"""',
        "from __future__ import annotations",
        "",
        "import uuid",
        "from pathlib import Path",
        "from typing import Any",
        "",
        *imports,
        "",
        f"MAX_SIZE_BYTES = {max_bytes!r}",
        f"DIRECTORY = Path({directory!r})",
        "",
        "",
        *gate_class,
        f"class {pascal}UploadStorage:",
        f'    """Validate and store uploaded files for the {entity_name} route."""',
        "",
        "    def __init__(self, directory: Path | None = None) -> None:",
        "        self._directory = directory or DIRECTORY",
        "        self._pipeline = FileUploadPipeline([",
        f"            {validators_src},",
        "        ])",
        "",
        "    async def save(",
        "        self,",
        "        upload: FileUpload,",
        "    ) -> Result[dict[str, Any], FileValidationError]:",
        '        """Validate `upload` and store it; returns file metadata."""',
        "        candidate = FileUpload(",
        '            filename=upload.filename or "upload",',
        '            content_type=upload.content_type or "application/octet-stream",',
        "            size=upload.size or 0,",
        "            file=upload.file,",
        "        )",
        "        verdict = await self._pipeline.process(candidate)",
        "        if verdict.is_err():",
        "            return Err(verdict.unwrap_err())",
        '        saved_name = f"{uuid.uuid4().hex}{Path(candidate.filename).suffix.lower()}"',
        "        target = self._directory / saved_name",
        "        try:",
        "            await candidate.save_to(target, base_dir=self._directory)",
        "        except (OSError, ValueError) as exc:",
        "            return Err(FileValidationError(message=str(exc)))",
        "        return Ok(",
        "            {",
        '                "filename": candidate.filename,',
        '                "saved_as": saved_name,',
        '                "path": str(target),',
        '                "size": candidate.size,',
        '                "content_type": candidate.content_type,',
        "            }",
        "        )",
        "",
    ]
    return "\n".join(lines)


def emit_upload_controller(
    entity_name: str,
    route_path: str,
    config: FileUploadConfig,
    mods: dict[str, str] | None = None,
) -> str:
    """Render the upload controller for *entity_name*."""
    mods = mods or DEFAULT_LAYOUT.module_names()
    pascal = pascal_entity(entity_name)
    storage_pascal = f"{pascal}UploadStorage"
    route_path = route_path.rstrip("/") or f"/{entity_name}"
    storage_module = f"{mods['uploads']}.{config.name}_upload_storage"

    return "\n".join(
        [
            _HEADER,
            f'"""{pascal} upload endpoint (file-upload node)."""',
            "from __future__ import annotations",
            "",
            "from typing import Any",
            "",
            "from lexigram.web import Controller, post",
            "from lexigram.web.exceptions import BadRequestError",
            "from lexigram.web.uploads import FileUpload, FileValidationError",
            "from starlette.requests import Request",
            "",
            f"from {storage_module} import {storage_pascal}",
            "",
            "",
            f"class {pascal}UploadController(Controller):",
            f'    """POST {route_path}/upload - store one uploaded file."""',
            "",
            f"    def __init__(self, storage: {storage_pascal}) -> None:",
            "        super().__init__()",
            "        self.storage = storage",
            "",
            f'    @post("{route_path}/upload")',
            "    async def upload(self, request: Request) -> dict[str, Any]:",
            '        """Accept `multipart/form-data` with a `file` field."""',
            '        content_type = request.headers.get("content-type", "")',
            '        if "multipart/form-data" not in content_type:',
            "            raise BadRequestError(",
            '                "Expected multipart/form-data with a `file` field"',
            "            )",
            "        form = await request.form()",
            '        raw = form.get("file")',
            "        if raw is None:",
            '            raise BadRequestError("Missing `file` field")',
            "        upload = FileUpload(",
            '            filename=getattr(raw, "filename", "") or "upload",',
            '            content_type=getattr(raw, "content_type", "")',
            '                or "application/octet-stream",',
            '            size=int(getattr(raw, "size", 0) or 0),',
            "            file=raw,",
            "        )",
            "        verdict = await self.storage.save(upload)",
            "        if verdict.is_err():",
            "            raise BadRequestError(verdict.unwrap_err().message)",
            '        return {"file": verdict.unwrap()}',
            "",
        ]
    )

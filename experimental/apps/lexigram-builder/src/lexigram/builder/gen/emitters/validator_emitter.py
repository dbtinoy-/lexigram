"""Validator node emission (nodes plan N3.1).

The framework has no validator/constraint generator, so the builder emits a
standalone, reusable constraint module per wired entity (open question 7's
default — composing into contract models is a documented stretch goal):

``src/app/validators/<entity>.py``
    ``<ENTITY>_CONSTRAINTS`` — field → Pydantic ``Field`` kwargs, ready for
    ``Field(**<ENTITY>_CONSTRAINTS["price"])`` in your models — plus
    ``validate_<entity>_payload(data) -> dict[str, str]`` which checks a raw
    payload dict against the same constraints without a model.

Constraints use a small ``kwarg=value`` grammar shared with the FE inspector
(see :func:`lexigram.builder.graph.validation.parse_constraint_expr`).
"""

from __future__ import annotations

from lexigram.builder.gen.emitters.context import pascal_entity
from lexigram.builder.graph.models import ValidatorConfig

_HEADER = "# generated by lexigram-builder - do not edit"

_SUPPORTED = (
    "ge", "le", "gt", "lt", "min_length", "max_length", "multiple_of",
)
def format_constraint_value(raw: str) -> str:
    """Render a constraint value as a Python literal.

    Numeric kwargs become int (preferred) or float; ``pattern`` stays a
    quoted regex. Raises ``ValueError`` for junk — callers validate first.
    """
    raw = raw.strip()
    try:
        return repr(int(raw))
    except ValueError:
        pass
    try:
        return repr(float(raw))
    except ValueError as exc:
        raise ValueError(f"constraint value {raw!r} is not a number") from exc


def parse_constraints(
    rules: tuple[tuple[str, str], ...],
) -> dict[str, dict[str, str]]:
    """Group ``(field, expr)`` rules into ``{field: {kwarg: literal}}``.

    Values are already-validated literal *strings*; rendering happens via
    :func:`format_constraint_value` (numeric) or ``repr`` (pattern).
    """
    out: dict[str, dict[str, str]] = {}
    for field, expr in rules:
        for token in expr.split(","):
            token = token.strip()
            if not token:
                continue
            key, _, raw = token.partition("=")
            key = key.strip()
            value = (
                raw if key == "pattern" else format_constraint_value(raw)
            )
            out.setdefault(field, {})[key] = value
    return out


def emit_validator_module(entity_name: str, config: ValidatorConfig) -> str:
    """Render ``src/app/validators/<entity>.py`` for *config*."""
    pascal = pascal_entity(entity_name)
    upper = entity_name.upper()
    constraints = parse_constraints(
        config.rules if config.enabled else ()
    )

    lines: list[str] = [
        _HEADER,
        f'"""Reusable field constraints for {pascal} payloads (validator node).',
        "",
        "Standalone constraint set (nodes plan N3.1): apply the kwargs to your",
        f"models via ``Field(**{upper}_CONSTRAINTS[field])``, or use",
        f"``validate_{entity_name}_payload`` for a ready-made dict check",
        "(no model required). Composing into contract DTOs is a planned",
        "follow-up (open question 7).",
        '"""',
        "from __future__ import annotations",
        "",
        "import re",
        "from typing import Any",
        "",
    ]

    if constraints:
        lines.append(f"{upper}_CONSTRAINTS: dict[str, dict[str, Any]] = {{")
        for field, kwargs in constraints.items():
            inner = ", ".join(
                f"{k!r}: {v!r}" if k == "pattern" else f"{k!r}: {v}"
                for k, v in kwargs.items()
            )
            lines.append(f'    "{field}": {{{inner}}},')
        lines.append("}")
    else:
        lines.append(f"{upper}_CONSTRAINTS: dict[str, dict[str, Any]] = {{}}")

    lines.extend(
        [
            "",
            f'_NUMERIC_KWARGS = frozenset({{{", ".join(map(repr, _SUPPORTED))}}})',
            "",
            "",
            f"def validate_{entity_name}_payload(data: dict[str, Any]) -> dict[str, str]:",
            f'    """Check *data* against {upper}_CONSTRAINTS.',
            "",
            "    Returns ``{field: message}``; an empty dict means the payload",
            "    satisfies every declared constraint. Fields absent from the",
            "    payload are skipped (required-ness stays a model concern).",
            '    """',
            "    errors: dict[str, str] = {}",
            f"    for field, rules in {upper}_CONSTRAINTS.items():",
            "        if field not in data:",
            "            continue",
            "        value = data[field]",
            "        for kwarg, limit in rules.items():",
            "            if kwarg == \"pattern\":",
            "                if not isinstance(value, str) or re.search(limit, value) is None:",
            "                    errors[field] = f\"does not match pattern {limit!r}\"",
            "                    break",
            "                continue",
            "            if kwarg in (\"min_length\", \"max_length\"):",
            "                if not isinstance(value, str):",
            "                    errors[field] = f\"{kwarg}={limit} needs a string value\"",
            "                    break",
            "                if kwarg == \"min_length\" and len(value) < limit:",
            "                    errors[field] = f\"must be a string of at least {limit} character(s)\"",
            "                    break",
            "                if kwarg == \"max_length\" and len(value) > limit:",
            "                    errors[field] = f\"must be a string of at most {limit} character(s)\"",
            "                    break",
            "                continue",
            "            if isinstance(value, bool) or not isinstance(value, (int, float)):",
            "                errors[field] = f\"{kwarg}={limit} needs a numeric value\"",
            "                break",
            "            if kwarg == \"ge\" and not value >= limit:",
            "                errors[field] = f\"must be >= {limit}\"",
            "                break",
            "            if kwarg == \"le\" and not value <= limit:",
            "                errors[field] = f\"must be <= {limit}\"",
            "                break",
            "            if kwarg == \"gt\" and not value > limit:",
            "                errors[field] = f\"must be > {limit}\"",
            "                break",
            "            if kwarg == \"lt\" and not value < limit:",
            "                errors[field] = f\"must be < {limit}\"",
            "                break",
            "            if kwarg == \"multiple_of\" and value % limit != 0:",
            "                errors[field] = f\"must be a multiple of {limit}\"",
            "                break",
            "    return errors",
            "",
        ]
    )
    return "\n".join(lines)

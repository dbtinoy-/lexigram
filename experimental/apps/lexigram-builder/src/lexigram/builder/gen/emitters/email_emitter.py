"""Emitters for the ``email_template`` node kind (nodes plan N4.3).

Screen-managed kind (Emails modal) that graduates to real generation. Per
enabled template one ``Mailable`` subclass module is emitted, plus two
shared modules when any template is enabled:

* ``src/app/emails/<name>.py`` — ``<PascalName>(Mailable)`` whose
  constructor takes the declared merge variables and whose ``to_message()``
  renders ``{{var}}`` placeholders in the subject/HTML/text templates
  (HTML values are escaped with the framework's ``escape_html``).
* ``src/app/emails/mailer.py`` — ``build_mailer()`` returning the
  framework's ``ConsoleMailer`` by default or an env-configured
  ``SMTPMailer`` (``LEX_EMAIL_HOST`` et al.).
* ``src/app/emails/__init__.py`` — re-exports of the emitted classes.

The ``triggers`` knob is documentation-only for v1.x: delivery wiring (who
sends the email when a trigger fires) is not emitted yet — documented here,
in TASKS.md, and in each emitted module's docstring.
"""

from __future__ import annotations

from lexigram.builder.gen.emitters.context import pascal_entity
from lexigram.builder.graph.models import EmailTemplateConfig

_HEADER = "# Generated by lexigram-builder. Do not edit; regenerate instead."


def _string_literal_chunks(value: str, indent: str = "        ") -> list[str]:
    """Render *value* as adjacent single-quoted literal lines (<=88 cols).

    Each source line of *value* becomes one ``repr()`` chunk (trailing
    newline folded into the literal) so adjacent-literal concatenation
    reconstructs the exact string. ``repr`` escapes quotes and backslashes,
    so user template text can never break the emitted syntax.
    """
    chunks: list[str] = []
    lines = value.split("\n")
    for index, line in enumerate(lines):
        text = line + ("\n" if index < len(lines) - 1 else "")
        chunks.append(f"{indent}{text!r}")
    if not chunks:
        chunks.append(f'{indent}""')
    return chunks


def _literal_assignment(name: str, value: str) -> list[str]:
    """Emit ``NAME: str = (`` ... chunks ... ``)`` for a template string."""
    if value == "":
        return [f"{name}: str = ''"]
    out = [f"{name}: str = ("]
    out.extend(_string_literal_chunks(value))
    out.append(")")
    return out


def emit_email_module(config: EmailTemplateConfig) -> str:
    """Emit ``src/app/emails/<name>_email.py`` for one enabled template."""
    class_name = pascal_entity(config.name)
    var_names = [v.name for v in config.variables]
    defaults = {v.name: v.default for v in config.variables}
    lines: list[str] = [
        _HEADER,
        "",
        f'"""Email template {config.name!r} (email-template node).',
        "",
        "Emitted for the enabled email_template node of the same name.",
        "``triggers`` are documentation-only in v1.x: nothing calls",
        "``build_mailer().send(...)`` automatically yet — wire the send in",
        "the handler that owns the business event.",
        '"""',
        "from __future__ import annotations",
        "",
        "import re",
        "",
        "from lexigram.contracts.mailer import EmailMessage",
        "from lexigram.notification import Mailable",
        "from lexigram.notification.mailer.mailable import escape_html",
        "",
    ]
    lines.append(f"TEMPLATE_NAME: str = {config.name!r}")
    lines.extend(_literal_assignment("SUBJECT", config.subject))
    lines.extend(_literal_assignment("HTML_TEMPLATE", config.html_template))
    lines.extend(_literal_assignment("TEXT_TEMPLATE", config.text_template))
    lines.append(f"FROM_EMAIL: str = {config.from_email!r}")
    lines.append(f"REPLY_TO: str = {config.reply_to!r}")
    if var_names:
        lines.append("VARIABLES: tuple[str, ...] = (")
        lines.extend(f"    {name!r}," for name in var_names)
        lines.append(")")
    else:
        lines.append("VARIABLES: tuple[str, ...] = ()")
    if config.triggers:
        lines.append("TRIGGERS: tuple[str, ...] = (")
        lines.extend(f"    {t!r}," for t in config.triggers)
        lines.append(")")
    else:
        lines.append("TRIGGERS: tuple[str, ...] = ()")
    lines += [
        "",
        '_PLACEHOLDER = re.compile(r"\\{\\{\\s*([a-z_][a-z0-9_]*)\\s*\\}\\}")',
        "",
        "",
        "def _render(template: str, values: dict[str, str]) -> str:",
        '    """Substitute ``{{var}}`` placeholders.',
        "",
        "    Unknown references pass through untouched so a typo degrades",
        "    to a visible literal rather than an empty subject line.",
        '    """',
        "    return _PLACEHOLDER.sub(",
        "        lambda m: values.get(m.group(1), m.group(0)), template",
        "    )",
        "",
        "",
        f"class {class_name}(Mailable):",
        f'    """{config.description or f"The {config.name} email."}"""',
        "",
        "    def __init__(",
        "        self,",
        "        *,",
        "        to: str,",
    ]
    for name in var_names:
        lines.append(f"        {name}: str = {defaults[name]!r},")
    lines += [
        "    ) -> None:",
        "        \"\"\"Store the recipient and merge variables.\"\"\"",
        "        self.to = to",
    ]
    for name in var_names:
        lines.append(f"        self.{name} = {name}")
    lines += [
        "",
        "    def to_message(self) -> EmailMessage:",
        "        text_values = {",
    ]
    for name in var_names:
        lines.append(f"            {name!r}: str(self.{name}),")
    lines.append("        }")
    lines.append("        html_values = {")
    for name in var_names:
        lines.append(
            f"            {name!r}: escape_html(str(self.{name})),"
        )
    lines += [
        "        }",
        "        return EmailMessage(",
        "            to=[self.to],",
        "            subject=_render(SUBJECT, text_values),",
        "            html_body=_render(HTML_TEMPLATE, html_values),",
        "            body=(",
        "                _render(TEXT_TEMPLATE, text_values)",
        "                if TEXT_TEMPLATE",
        '                else ""',
        "            ),",
        "            from_email=FROM_EMAIL or None,",
        "            reply_to=REPLY_TO or None,",
        "        )",
        "",
    ]
    return "\n".join(lines) + "\n"


def emit_emails_init(configs: list[EmailTemplateConfig]) -> str:
    """Emit ``src/app/emails/__init__.py`` re-exporting the templates."""
    lines: list[str] = [
        _HEADER,
        "",
        '"""Transactional email templates (email_template nodes).',
        "",
        "Each enabled template emits a ``Mailable`` subclass module here;",
        "``mailer.build_mailer()`` returns the delivery backend.",
        '"""',
        "from __future__ import annotations",
        "",
    ]
    pairs = [
        (config.name, pascal_entity(config.name)) for config in configs
    ]
    for module, class_name in pairs:
        lines.append(f"from app.emails.{module} import {class_name}")
    lines.append("")
    lines.append("__all__ = [")
    lines.extend(f'    "{name}",' for _, name in pairs)
    lines.append("]")
    lines.append("")
    return "\n".join(lines) + "\n"


def emit_mailer_helper() -> str:
    """Emit ``src/app/emails/mailer.py`` with ``build_mailer()``."""
    lines: list[str] = [
        _HEADER,
        "",
        '"""Delivery backend for this app\'s email templates.',
        "",
        "``build_mailer()`` returns the framework's zero-config"
        " ``ConsoleMailer``",
        "(every message is logged, never sent) unless ``LEX_EMAIL_HOST`` is",
        "set, in which case an ``SMTPMailer`` is configured from the",
        "``LEX_EMAIL_*`` environment variables.",
        '"""',
        "from __future__ import annotations",
        "",
        "import os",
        "",
        "from lexigram.contracts.mailer.protocols import MailerProtocol",
        (
            "from lexigram.notification.mailer.console_mailer import"
            " ConsoleMailer"
        ),
        "from lexigram.notification.mailer.smtp_mailer import SMTPMailer",
        "",
        "",
        "def build_mailer() -> MailerProtocol:",
        '    """Console mailer by default; SMTP when LEX_EMAIL_HOST is set."""',
        '    host = os.environ.get("LEX_EMAIL_HOST")',
        "    if not host:",
        "        return ConsoleMailer()",
        "    return SMTPMailer(",
        "        host=host,",
        '        port=int(os.environ.get("LEX_EMAIL_PORT", "587")),',
        '        username=os.environ.get("LEX_EMAIL_USER") or None,',
        '        password=os.environ.get("LEX_EMAIL_PASSWORD") or None,',
        '        use_tls=os.environ.get("LEX_EMAIL_TLS", "1") != "0",',
        '        from_email=os.environ.get("LEX_EMAIL_FROM") or None,',
        "    )",
        "",
    ]
    return "\n".join(lines) + "\n"

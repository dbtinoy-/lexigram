from __future__ import annotations

from lexigram.builder.gen.emitters.context import pascal_entity, snake_case
from lexigram.builder.graph.models import SagaConfig

_HEADER = "# Generated by lexigram-builder. Do not edit; regenerate instead."


def emit_saga_module(config: SagaConfig) -> str:
    pascal = pascal_entity(config.name)
    snake = snake_case(config.name)
    doc = config.description or f"{pascal} saga orchestrator."
    return f'''{_HEADER}
"""{doc}

Generated scaffold — define the forward steps and their compensating
actions, then run the saga from your application layer.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Awaitable, Callable

from lexigram.logging import get_logger

logger = get_logger(__name__)

StepAction = Callable[[dict[str, Any]], Awaitable[None]]


@dataclass(slots=True)
class SagaStep:
    """A single saga step with its compensating action."""

    name: str
    action: StepAction
    compensation: StepAction | None = None


@dataclass(slots=True)
class {pascal}Saga:
    """Orchestrate the {pascal} flow with compensations."""

    steps: list[SagaStep] = field(default_factory=list)
    completed: list[SagaStep] = field(default_factory=list)

    def add_step(
        self,
        name: str,
        action: StepAction,
        compensation: StepAction | None = None,
    ) -> None:
        """Append a step to the saga."""
        self.steps.append(SagaStep(name=name, action=action, compensation=compensation))

    async def execute(self, context: dict[str, Any]) -> None:
        """Run all steps, compensating completed ones on failure."""
        for step in self.steps:
            try:
                logger.info("saga_step_started", saga={snake!r}, step=step.name)
                await step.action(context)
                self.completed.append(step)
            except Exception:
                logger.error("saga_step_failed", saga={snake!r}, step=step.name)
                await self._compensate(context)
                raise
        logger.info("saga_completed", saga={snake!r})

    async def _compensate(self, context: dict[str, Any]) -> None:
        """Undo completed steps in reverse order."""
        for step in reversed(self.completed):
            if step.compensation is not None:
                logger.warning("saga_compensating", saga={snake!r}, step=step.name)
                await step.compensation(context)
        self.completed.clear()
'''

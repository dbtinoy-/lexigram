"""Emitters for the ``search_index`` node kind (N3.2).

Three artifacts per search index, keyed off ``effective_engine``:

* ``fts``    -> alembic revision ``b{n:04d}_{entity}_search_fts.py`` (SQLite
  FTS5 external-content virtual table + sync triggers) **plus** the repository
  (MATCH / bm25 ranked) **plus** the ``GET <route>/search`` controller.
* ``like``   -> repository (CAST ... LIKE) + controller only, no migration.
* ``meilisearch`` / ``elasticsearch`` -> honest fallback to ``like`` with a
  note in the emitted repository docstring; no external engine is provisioned.

``fuzzy`` / ``suggestions`` node knobs are reserved for v1.x: they are stored
on the config and validated, but have no emission effect yet (documented in
TASKS.md and the emitted docstrings).

The FTS5 table uses SQLite's external-content pattern keyed on ``rowid``
(``content_rowid='rowid'``). An explicit id column variant is known-broken
(UPDATE trigger corrupts the index -> "database disk image is malformed");
see docs/LEXIGRAM_FRAMEWORK_BUGS.md before touching this.
"""

from __future__ import annotations

from lexigram.builder.gen.emitters.context import pascal_entity, table_name
from lexigram.builder.graph.models import SearchIndexConfig

_EXTERNAL_ENGINES: frozenset[str] = frozenset({"meilisearch", "elasticsearch"})

_HEADER = (
    "# Generated by lexigram-builder. Do not edit; regenerate instead.\n"
)


def effective_engine(config: SearchIndexConfig) -> str:
    """Resolve the engine actually emitted for this search index.

    ``fts`` and ``like`` are emitted natively. External engines
    (``meilisearch`` / ``elasticsearch``) are not backend-backed yet and fall
    back to ``like``; the fallback is documented in the emitted repository.
    """
    if config.engine in _EXTERNAL_ENGINES:
        return "like"
    return config.engine


def _boost_weights(
    fields: tuple[str, ...], boost: dict[str, float] | None
) -> list[str]:
    """bm25() weight list in field order (boost value or default 1.0)."""
    boost = boost or {}
    return [f"{boost.get(field, 1.0):g}" for field in fields]


def emit_search_migration(
    entity_name: str,
    config: SearchIndexConfig,
    *,
    prev_revision: str | None,
    revision: str,
) -> str:
    """Render the alembic revision creating the entity's FTS5 index.

    External-content FTS5 keyed on ``rowid`` + a one-shot rebuild + AI/AU/AD
    sync triggers. ``prev_revision`` chains onto the last entity migration so
    the search table exists after the entity table.
    """
    table = table_name(entity_name)
    fields = config.fields
    fts_table = f"{table}_fts"
    col_list = ", ".join(f'"{f}"' for f in fields)
    new_cols = ", ".join(f'NEW."{f}"' for f in fields)
    old_cols = ", ".join(f'OLD."{f}"' for f in fields)
    down_rev = repr(prev_revision) if prev_revision else "None"
    header_note = (
        "External engines are not provisioned yet; pick engine=like to skip"
        " this migration entirely."
        if config.engine in _EXTERNAL_ENGINES
        else "FTS5 MATCH + bm25 ranking on the columns below."
    )

    # Build the raw SQL statements here and embed each via %r so the emitted
    # migration is always syntactically valid regardless of quoting.
    create_sql = (
        f"CREATE VIRTUAL TABLE IF NOT EXISTS {fts_table} "
        f"USING fts5({col_list}, content='{table}', content_rowid='rowid')"
    )
    rebuild_sql = f"INSERT INTO {fts_table}({fts_table}) VALUES('rebuild')"
    ai_sql = (
        f'CREATE TRIGGER {fts_table}_ai AFTER INSERT ON "{table}" BEGIN '
        f"INSERT INTO {fts_table}(rowid, {col_list}) "
        f"VALUES (NEW.rowid, {new_cols}); END"
    )
    ad_sql = (
        f'CREATE TRIGGER {fts_table}_ad AFTER DELETE ON "{table}" BEGIN '
        f"INSERT INTO {fts_table}({fts_table}, rowid, {col_list}) "
        f"VALUES ('delete', OLD.rowid, {old_cols}); END"
    )
    au_sql = (
        f'CREATE TRIGGER {fts_table}_au AFTER UPDATE ON "{table}" BEGIN '
        f"INSERT INTO {fts_table}({fts_table}, rowid, {col_list}) "
        f"VALUES ('delete', OLD.rowid, {old_cols}); "
        f"INSERT INTO {fts_table}(rowid, {col_list}) "
        f"VALUES (NEW.rowid, {new_cols}); END"
    )

    def _exec(sql: str, indent: str = "    ") -> str:
        return f"{indent}op.execute(\n{indent}    {sql!r}\n{indent})"

    lines: list[str] = [
        _HEADER.rstrip("\n"),
        f'"""FTS5 search index for {table}. {header_note}"""',
        "",
        "from __future__ import annotations",
        "",
        "import sqlalchemy as sa",
        "from alembic import op",
        "",
        f"revision: str = {revision!r}",
        "down_revision: str | None = " + down_rev,
        "branch_labels = None",
        "depends_on = None",
        "",
        "",
        "def upgrade() -> None:",
        _exec(create_sql),
        "    # One-shot rebuild backfills existing rows.",
        _exec(rebuild_sql),
        "    # AFTER INSERT: index the new row (keyed on rowid).",
        _exec(ai_sql),
        "    # AFTER DELETE: 'delete' command removes the row from the index.",
        _exec(ad_sql),
        "    # AFTER UPDATE: delete-tuple then re-insert.",
        _exec(au_sql),
        "",
        "",
        "def downgrade() -> None:",
        f"    op.execute('DROP TRIGGER IF EXISTS {fts_table}_au')",
        f"    op.execute('DROP TRIGGER IF EXISTS {fts_table}_ad')",
        f"    op.execute('DROP TRIGGER IF EXISTS {fts_table}_ai')",
        f"    op.execute('DROP TABLE IF EXISTS {fts_table}')",
        "",
    ]
    return "\n".join(lines)


def emit_search_repository(entity_name: str, config: SearchIndexConfig) -> str:
    """Render ``src/app/repositories/<entity>_search_repository.py``."""
    engine = effective_engine(config)
    pascal = pascal_entity(entity_name)
    table = table_name(entity_name)
    fields = config.fields
    external = config.engine in _EXTERNAL_ENGINES

    if external:
        header_note = (
            f"LIKE-based fallback (engine {config.engine!r} is not backend-backed"
            " yet; swap in an external engine here when you outgrow SQLite)."
        )
    elif engine == "fts":
        header_note = "SQLite FTS5 MATCH with bm25 ranking (boost weights)."
    else:
        header_note = "LIKE-based search (engine: like)."

    # DatabaseService implements execute_query (QueryResult iterates as
    # dict rows); the protocol's fetch_all/fetch_one are declared but not
    # implemented by the concrete provider (see LEXIGRAM_FRAMEWORK_BUGS).
    if engine == "fts":
        weights = ", ".join(_boost_weights(fields, config.boost))
        search_sql = (
            f"SELECT t.* FROM {table} t "
            f"JOIN {table}_fts fts ON fts.rowid = t.rowid "
            f"WHERE {table}_fts MATCH ? "
            f"ORDER BY bm25({table}_fts, {weights}) LIMIT ?"
        )
        search_implementation = "\n".join(
            [
                "        # Prefix-search the quoted term; quotes neutralize input.",
                '        fts_query = \'"\' + query.replace(\'"\', "") + \'"*\'',
                "        result = await self._provider.execute_query(",
                f"            {search_sql!r},",
                "            [fts_query, limit],",
                "        )",
                "        return [dict(row) for row in result]",
            ]
        )
    else:
        like_clauses = " OR ".join(f'CAST("{f}" AS TEXT) LIKE ?' for f in fields)
        search_sql = f"SELECT * FROM {table} WHERE {like_clauses} LIMIT ?"
        params_items = ", ".join(["pattern"] * len(fields))
        search_implementation = "\n".join(
            [
                '        pattern = f"%{query}%"',
                "        result = await self._provider.execute_query(",
                f"            {search_sql!r},",
                f"            [{params_items}, limit],",
                "        )",
                "        return [dict(row) for row in result]",
            ]
        )

    return "\n".join(
        [
            _HEADER,
            f'"""{pascal} search repository (search-index node).',
            "",
            header_note,
            "The fuzzy/suggestions node knobs are reserved for v1.x and have",
            "no emission effect yet.",
            "",
            "DatabaseService implements execute_query (QueryResult iterates",
            "as dict rows); the protocol's fetch_all/fetch_one are declared",
            "but not implemented by the concrete provider (see",
            "LEXIGRAM_FRAMEWORK_BUGS.md).",
            '"""',
            "from __future__ import annotations",
            "",
            "from typing import Any",
            "",
            "from lexigram.contracts import DatabaseProviderProtocol",
            "",
            "",
            f"class {pascal}SearchRepository:",
            f'    """Search over the {table} table.',
            "",
            "    Injected like any other repository; runs raw SQL through the",
            "    database provider (no ORM entities involved).",
            '    """',
            "",
            "    def __init__(self, provider: DatabaseProviderProtocol) -> None:",
            "        self._provider = provider",
            "",
            "    async def search(",
            "        self,",
            "        query: str,",
            "        *,",
            "        limit: int = 20,",
            "    ) -> list[dict[str, Any]]:",
            '        """Return matching rows, best-first (empty query -> [])."""',
            "        query = query.strip()",
            "        if not query:",
            "            return []",
            search_implementation,
            "",
        ]
    )


def emit_search_controller(entity_name: str, route_path: str) -> str:
    """Render ``src/app/controllers/<entity>_search_controller.py``."""
    pascal = pascal_entity(entity_name)
    route_path = route_path.rstrip("/") or f"/{entity_name}"
    pascal_repo = f"{pascal}SearchRepository"
    return "\n".join(
        [
            _HEADER,
            f'"""{pascal} search endpoint (search-index node)."""',
            "from __future__ import annotations",
            "",
            "from typing import Any",
            "",
            "from lexigram.web import Controller, get",
            "",
            f"from app.repositories.{entity_name}_search_repository import (",
            f"    {pascal_repo},",
            ")",
            "",
            "",
            f"class {pascal}SearchController(Controller):",
            f'    """GET {route_path}/search - full-text search over {entity_name}."""',
            "",
            f"    def __init__(self, repo: {pascal_repo}) -> None:",
            "        super().__init__()",
            "        self.repo = repo",
            "",
            f'    @get("{route_path}/search")',
            "    async def search(",
            "        self,",
            '        q: str = "",',
            "        limit: int = 20,",
            "    ) -> dict[str, Any]:",
            '        """Search rows; `q` is the query, `limit` caps results."""',
            "        items = await self.repo.search(q, limit=max(1, min(limit, 100)))",
            '        return {"items": items, "q": q, "count": len(items)}',
            "",
        ]
    )

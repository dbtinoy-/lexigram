"""Route controller emitter: one aggregated controller file per entity."""

from __future__ import annotations

from lexigram.builder.gen.emitters.context import (
    pascal_entity,
    pluralize,
    snake_case,
)
from lexigram.builder.graph.models import EntityConfig

GENERATED_HEADER = "# generated by lexigram-builder - do not edit\n"

_OP_METHODS = {
    "create": "create",
    "get": "get",
    "list": "list_all",
    "update": "update",
    "delete": "delete",
}


def emit_controller_file(
    entity: EntityConfig,
    ops: tuple[str, ...],
) -> tuple[str, str]:
    """Return ``(rel_path, content)`` for the entity's aggregated controller.

    Args:
        entity: Bound entity config.
        ops: Aggregated, de-duplicated ops from every route wired to the
            entity, in canvas order.
    """
    entity_name = entity.name
    pascal = pascal_entity(entity_name)
    resource = pluralize(snake_case(entity_name))
    prefix = ""
    base_path = f"/{resource}"
    repo_type = f"{pascal}Repository"

    methods: list[str] = []
    selected_ops = [o for o in dict.fromkeys(ops) if o in _OP_METHODS]

    if "create" in selected_ops:
        methods.append(
            f"""    @post("{base_path}", status_code=201)
    async def create(self, data: {pascal}Create) -> Result[dict, DomainError]:
        try:
            entity = {pascal}(**data.model_dump())
        except PydanticValidationError as exc:
            return Err(ValidationError(str(exc)))
        created = await self.repo.create(entity)
        return Ok(created.model_dump())
"""
        )
    if "list" in selected_ops:
        methods.append(
            f"""    @get("{base_path}")
    async def list_all(self, limit: int = 50) -> Result[list[dict], DomainError]:
        rows = await self.repo.list_all(limit=limit)
        return Ok([row.model_dump() for row in rows])
"""
        )
    if "get" in selected_ops:
        methods.append(
            f"""    @get("{base_path}/{{item_id}}")
    async def get(self, item_id: str) -> Result[dict, DomainError]:
        found = await self.repo.get(item_id)
        if found is None:
            return Err(NotFoundError(f"unknown {{resource}} {{item_id!r}}"))
        return Ok(found.model_dump())
"""
        )
    if "update" in selected_ops:
        methods.append(
            f"""    @put("{base_path}/{{item_id}}")
    async def update(
        self, item_id: str, data: {pascal}Update
    ) -> Result[dict, DomainError]:
        found = await self.repo.get(item_id)
        if found is None:
            return Err(NotFoundError(f"unknown {{resource}} {{item_id!r}}"))
        patch = data.model_dump(exclude_unset=True)
        for key, value in patch.items():
            setattr(found, key, value)
        saved = await self.repo.update(found)
        return Ok(saved.model_dump())
"""
        )
    if "delete" in selected_ops:
        methods.append(
            f"""    @delete("{base_path}/{{item_id}}")
    async def delete(self, item_id: str) -> Result[bool, DomainError]:
        deleted = await self.repo.delete(item_id)
        if not deleted:
            return Err(NotFoundError(f"unknown {{resource}} {{item_id!r}}"))
        return Ok(True)
"""
        )

    body = "\n\n".join(methods)
    content = f'''{GENERATED_HEADER}
from __future__ import annotations

from pydantic import ValidationError as PydanticValidationError

from lexigram.contracts.exceptions.domain import (
    DomainError,
    NotFoundError,
    ValidationError,
)
from lexigram.result import Err, Ok, Result
from lexigram.web import Controller
from lexigram.web.routing.decorators import delete, get, post, put

from app.models.{entity_name} import {pascal}, {pascal}Create, {pascal}Update
from app.repositories.{entity_name}_repository import {repo_type}


class {pascal}Controller(Controller):
    """CRUD endpoints for {resource}."""

    def __init__(self, repo: {repo_type}) -> None:
        self.repo = repo


{body}
'''
    rel = f"src/app/controllers/{snake_case(entity_name)}_controller.py"
    return rel, content

"""Emit framework ``Controller`` wrappers for inbound webhook triggers.

The framework ``webhook`` generator (``lexigram-web``) produces a payload
Pydantic model plus a handler class with HMAC signature verification
(``<name>_webhook.py``). That module is a plain ASGI handler and is **not** a
framework ``Controller``, so ``WebModule.configure(controllers=[...])`` would
not mount it. This emitter wraps each webhook in a thin framework
``Controller`` that exposes a ``POST`` route and delegates to the generated
handler.

The handler's shared secret is read from the environment (server-side) rather
than from a request header — the generated ASGI shim in the framework template
incorrectly derives ``secret`` from ``request.headers`` (see docs/
LEXIGRAM_FRAMEWORK_BUGS.md, WEBHOOK-1).
"""

from __future__ import annotations

from lexigram.builder.gen.emitters.context import snake_case
from lexigram.builder.graph.models import WebhookConfig
from lexigram.contracts.cli.generators import pascal_case

GENERATED_HEADER = "# generated by lexigram-builder - do not edit\n"


def emit_webhook_controllers(
    webhooks: list[WebhookConfig] | tuple[WebhookConfig, ...],
    *,
    package: str = "app",
    jobs_by_trigger: dict[str, list[str]] | None = None,
) -> dict[str, str]:
    """Return ``{path: content}`` for each webhook's controller wrapper.

    Args:
        webhooks: Enabled webhook configs.
        package: Root import package for the generated app.
        jobs_by_trigger: Mapping of webhook name -> snake_case task names of
            the background jobs enqueued when the webhook fires.

    Returns:
        Mapping of project-relative file paths to their source.
    """
    jobs_by_trigger = jobs_by_trigger or {}
    files: dict[str, str] = {}
    for hook in sorted(webhooks, key=lambda w: w.name):
        stem = snake_case(hook.name)
        jobs = sorted(jobs_by_trigger.get(hook.name, []))
        files[f"src/{package}/controllers/{stem}_webhook_controller.py"] = (
            _webhook_controller(hook, stem, package, jobs)
        )
    return files


def _webhook_controller(
    hook: WebhookConfig, stem: str, package: str, jobs: list[str]
) -> str:
    pascal = pascal_case(hook.name)
    route = hook.path or f"/webhooks/{stem}"
    verify = hook.verify_signature
    secret_env = hook.secret_env or f"WEBHOOK_{stem.upper()}_SECRET"
    verify_literal = "True" if verify else "False"
    secret_line = (
        f'        secret = os.getenv("{secret_env}")\n'
        if verify
        else "        secret = None\n"
    )
    if jobs:
        jobs_param = ", tasks: TaskProvider"
        enqueue_block = "\n        # Fan out to connected background jobs.\n" + "".join(
            f"        await tasks.enqueue_job(\n"
            f"            JobProtocol(\n"
            f'                id=uuid4().hex,\n                name="{j}",\n'
            f'                args=(),\n                kwargs={{"payload": result}},\n'
            f"            )\n"
            f"        )\n"
            for j in jobs
        )
    else:
        jobs_param = ""
        enqueue_block = ""
    stdlib_imports = "import os\n" + ("from uuid import uuid4\n" if jobs else "")
    if jobs:
        third_party_imports = (
            "from lexigram.tasks import JobProtocol\n"
            "from lexigram.tasks.di.provider import TaskProvider\n"
            "from lexigram.web import Controller, post\n"
            "from starlette.requests import Request\n"
            "from starlette.responses import JSONResponse\n"
        )
    else:
        third_party_imports = (
            "from lexigram.web import Controller, post\n"
            "from starlette.requests import Request\n"
            "from starlette.responses import JSONResponse\n"
        )
    return f'''{GENERATED_HEADER}
"""{pascal} inbound webhook trigger.

Mounts a POST endpoint that delegates to the framework-generated
``{pascal}Webhook`` handler (payload validation + HMAC verification).
The shared secret is read from the ``{secret_env}`` environment variable
on the server — never from a request header.
"""

from __future__ import annotations

{stdlib_imports}
from {package}.webhooks.{stem}_webhook import {pascal}Webhook
{third_party_imports}

class {pascal}WebhookController(Controller):
    """Controller exposing the {pascal} webhook endpoint."""

    @post("{route}")
    async def receive(self, request: Request{jobs_param}) -> JSONResponse:
        """Receive and dispatch a {pascal} webhook event."""
        body = await request.body()
        # Starlette lower-cases request headers, while the framework webhook
        # handler looks up the signature key case-sensitively
        # ("X-Webhook-Signature"); present both casings (see docs/
        # LEXIGRAM_FRAMEWORK_BUGS.md WEBHOOK-2).
        headers = {{key: value for key, value in request.headers.items()}}
        if "x-webhook-signature" in headers:
            headers["X-Webhook-Signature"] = headers["x-webhook-signature"]
{secret_line}        handler = {pascal}Webhook(
            secret=secret,
            verify_signature={verify_literal},
        )
        # TODO: register event handlers via handler.register_handler(...)
        result = await handler.handle_request(body, headers)
        if result.get("status") == "error":
            return JSONResponse(result, status_code=400)
{enqueue_block}
        return JSONResponse(result, status_code=200)


__all__ = ["{pascal}WebhookController"]
'''


__all__ = ["emit_webhook_controllers"]

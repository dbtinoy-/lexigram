"""Per-entity file emitters: model+DTOs, repository, migration, smoke test."""

from __future__ import annotations

from lexigram.builder.gen.emitters.context import (
    pascal_entity,
    python_type_for,
    sql_type_for,
    table_name,
)
from lexigram.builder.graph.models import EntityConfig

GENERATED_HEADER = "# generated by lexigram-builder - do not edit\n"


def emit_entity_files(entity: EntityConfig) -> dict[str, str]:
    """Return every generated-app file for one entity node."""
    name = entity.name
    return {
        f"src/app/models/{name}.py": _model(name, entity),
        f"src/app/repositories/{name}_repository.py": _repository(name),
        f"migrations/versions/001_create_{table_name(name)}.py": _migration(entity),
        f"tests/test_crud_{name}.py": _crud_test(name),
    }


def _model(name: str, entity: EntityConfig) -> str:
    pascal = pascal_entity(name)

    def field_line(f_name: str, f_type: str, nullable: bool, default_none: bool) -> str:
        py = python_type_for(f_type)
        if nullable or default_none:
            return f"    {f_name}: {py} | None = None"
        return f"    {f_name}: {py}"

    model_fields = "\n".join(
        [
            '    id: str = Field(default_factory=lambda: str(uuid.uuid4()))',
            "    created_at: datetime = Field(",
            "        default_factory=lambda: datetime.now(timezone.utc)",
            "    )",
            "    updated_at: datetime = Field(",
            "        default_factory=lambda: datetime.now(timezone.utc)",
            "    )",
            *[
                field_line(f.name, f.type, f.nullable, default_none=False)
                for f in entity.fields
            ],
        ]
    )
    create_fields = (
        "\n".join(field_line(f.name, f.type, f.nullable, True) for f in entity.fields)
        or "    pass"
    )
    update_fields = (
        "\n".join(field_line(f.name, f.type, True, False) for f in entity.fields)
        or "    pass"
    )

    return f"""{GENERATED_HEADER}
from __future__ import annotations

import uuid
from datetime import datetime, timezone

from pydantic import BaseModel, ConfigDict, Field


class {pascal}(BaseModel):
    \"\"\"{pascal} entity.\"\"\"

    model_config = ConfigDict(from_attributes=True)

{model_fields}


class {pascal}Create(BaseModel):
    \"\"\"Payload for creating a {name}.\"\"\"

{create_fields}


class {pascal}Update(BaseModel):
    \"\"\"Partial patch payload for a {name}.\"\"\"

{update_fields}
"""


def _repository(name: str) -> str:
    pascal = pascal_entity(name)
    table = table_name(name)
    return f'''{GENERATED_HEADER}
from __future__ import annotations

from typing import Any

from lexigram.contracts import DatabaseProviderProtocol
from lexigram.sql.repositories.generic_repository import GenericRepository

from app.models.{name} import {pascal}


class _{pascal}Repo(GenericRepository[{pascal}, str]):
    """Row mapper bridge for {pascal}."""

    def _entity_to_dict(self, entity: {pascal}) -> dict[str, Any]:
        return entity.model_dump()

    def _row_to_entity(self, row: dict[str, Any]) -> {pascal}:
        return self.entity_class(**dict(row))


class {pascal}Repository:
    """Typed repository over the "{table}" table."""

    def __init__(self, provider: DatabaseProviderProtocol) -> None:
        self._provider = provider
        self._repo = _{pascal}Repo(
            provider=provider,
            table_name="{table}",
            entity_class={pascal},
            key_field="id",
        )

    async def create(self, entity: {pascal}) -> {pascal}:
        await self._provider.execute_insert("{table}", entity.model_dump())
        found = await self._repo.find_by_id(entity.id)
        assert found is not None
        return found

    async def get(self, key: str) -> {pascal} | None:
        return await self._repo.find_by_id(key)

    async def list_all(self, limit: int = 50) -> list[{pascal}]:
        return await self._repo.find(limit=limit, sort_by="created_at", sort_order="desc")

    async def update(self, entity: {pascal}) -> {pascal}:
        await self._provider.execute_update(
            "{table}",
            entity.model_dump(),
            '"id" = ?',
            [entity.id],
        )
        found = await self._repo.find_by_id(entity.id)
        assert found is not None
        return found

    async def delete(self, key: str) -> bool:
        return await self._repo.delete_by_id(key)
'''


def _migration(entity: EntityConfig) -> str:
    table = table_name(entity.name)
    column_lines = "\n".join(
        [
            '        sa.Column("id", sa.String(length=32), primary_key=True),',
            '        sa.Column("created_at", sa.DateTime(timezone=True), nullable=False),',
            '        sa.Column("updated_at", sa.DateTime(timezone=True), nullable=False),',
            *[
                f'        sa.Column("{f.name}", sa.{sql_sa_type(f.type)},'
                f" nullable={str(f.nullable).lower()}),"
                for f in entity.fields
            ],
        ]
    )
    return f"""{GENERATED_HEADER}
\"\"\"create {table}

Revision ID: 001_{table}
Revises:
Create Date: auto
\"\"\"
from __future__ import annotations

import sqlalchemy as sa
from alembic import op

revision = "001_{table}"
down_revision = None
branch_labels = None
depends_on = None


def upgrade() -> None:
    op.create_table(
        "{table}",
{column_lines}
    )


def downgrade() -> None:
    op.drop_table("{table}")
"""


def sql_sa_type(field_type: str) -> str:
    """SQLAlchemy column type for a palette field type."""
    return {
        "str": "String(length=255)",
        "int": "Integer",
        "float": "Float",
        "bool": "Boolean",
        "datetime": "DateTime(timezone=True)",
        "uuid": "String(length=32)",
    }.get(field_type, "String(length=255)")



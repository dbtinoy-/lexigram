"""Per-entity test emitter (model/repository/migration live in the CLIs)."""

from __future__ import annotations

from lexigram.builder.gen.emitters.context import table_name
from lexigram.builder.gen.layout import DEFAULT_LAYOUT
from lexigram.builder.graph.models import EntityConfig

GENERATED_HEADER = "# generated by lexigram-builder - do not edit\n"

_LITERAL_MAP = {
    "str": '"sample-value"',
    "text": '"sample text body"',
    "int": "42",
    "float": "4.2",
    "decimal": "4.20",
    "bool": "True",
    "datetime": '"2026-01-01T00:00:00+00:00"',
    "date": '"2026-01-01"',
    "time": '"00:00:00"',
    "uuid": '"0f8fad5b-d9cb-469f-a165-70867728950e"',
    "json": '{"sample": true}',
    "bytes": '"c2FtcGxl"',
    "enum": '"active"',
    "email": '"user@example.com"',
    "url": '"https://example.com/resource"',
    "phone": '"+15555550100"',
    "ipv4": '"127.0.0.1"',
    "ipv6": '"::1"',
    "filename": '"sample.txt"',
    "filepath": '"/tmp/sample.txt"',
}


def _field_literal(field_type: str) -> str:
    """Return a JSON-safe example value for every known field type."""
    return _LITERAL_MAP.get(field_type, '"sample-value"')


def crud_test_filename(entity: EntityConfig) -> str:
    """Relative tests/ filename for *entity*'s smoke test."""
    return f"tests/test_crud_{entity.name}.py"


def emit_crud_test(
    entity: EntityConfig,
    *,
    ops: frozenset[str] | None = None,
    path: str | None = None,
    mods: dict[str, str] | None = None,
) -> str:
    """HTTP smoke test for one routed entity (boots the full app).

    Args:
        entity: Entity configuration.
        ops: Set of CRUD operations to test. If None, tests all ops.
        path: API base path the controller serves (incl. leading slash).
            Defaults to the pluralized table name.
    """
    mods = mods or DEFAULT_LAYOUT.module_names()
    resource = (path or f"/{table_name(entity.name)}").strip("/")
    available_ops = ops or frozenset({"create", "get", "list", "update", "delete"})

    create_body = ", ".join(
        f'"{f.name}": {_field_literal(f.type)}' for f in entity.fields
    )
    update_body = (
        ", ".join(f'"{f.name}": {_field_literal(f.type)}' for f in entity.fields[:1])
        or '"id": "dummy"'
    )

    lines = [
        GENERATED_HEADER,
        "from __future__ import annotations",
        "",
        "import os",
        "import tempfile",
        "from typing import AsyncIterator",
        "",
        "import httpx",
        "import pytest",
        "",
        "",
        "@pytest.fixture",
        "async def client() -> AsyncIterator[httpx.AsyncClient]:",
        "    os.environ.setdefault(",
        '        "DATABASE_URL",',
        '        "sqlite+aiosqlite:///"',
        '        + tempfile.mkdtemp() + "/' + resource + '.db",',
        "    )",
        f"    from {mods['app']}.app import create_app",
        "",
        "    application = create_app()",
        "    await application.start()",
        "    try:",
        "        from lexigram.web.di.provider import WebProvider",
        "",
        "        web = await application.container.resolve(WebProvider)",
        "        transport = httpx.ASGITransport(app=web.starlette)",
        "        async with httpx.AsyncClient(",
        '            transport=transport, base_url="http://test"',
        "        ) as http:",
        "            yield http",
        "    finally:",
        "        await application.stop()",
        "",
        "",
    ]

    if "create" in available_ops and "get" in available_ops:
        lines.extend(
            [
                "async def test_create_get_roundtrip(client: httpx.AsyncClient) -> None:",
                '    created = await client.post("/' + resource + '", json={',
                "        " + create_body + ",",
                "    })",
                "    assert created.status_code == 201, created.text",
                '    item_id = created.json()["id"]',
                "",
                '    fetched = await client.get("/' + resource + '/" + item_id)',
                "    assert fetched.status_code == 200",
                "",
                "",
            ]
        )

    if "list" in available_ops:
        lines.extend(
            [
                "async def test_list_returns_items(client: httpx.AsyncClient) -> None:",
                '    resp = await client.get("/' + resource + '")',
                "    assert resp.status_code == 200",
                "    data = resp.json()",
                '    assert "items" in data',
                "",
                "",
            ]
        )

    if "update" in available_ops and "get" in available_ops:
        lines.extend(
            [
                "async def test_update_roundtrip(client: httpx.AsyncClient) -> None:",
                '    created = await client.post("/' + resource + '", json={',
                "        " + create_body + ",",
                "    })",
                "    assert created.status_code == 201",
                '    item_id = created.json()["id"]',
                "",
                '    updated = await client.put("/' + resource + '/" + item_id, json={',
                "        " + update_body + ",",
                "    })",
                "    assert updated.status_code == 200",
                "",
                "",
            ]
        )

    if "delete" in available_ops:
        lines.extend(
            [
                "async def test_delete_removes_item(client: httpx.AsyncClient) -> None:",
                '    created = await client.post("/' + resource + '", json={',
                "        " + create_body + ",",
                "    })",
                "    assert created.status_code == 201",
                '    item_id = created.json()["id"]',
                "",
                '    deleted = await client.delete("/' + resource + '/" + item_id)',
                "    assert deleted.status_code == 200",
                "",
                '    missing = await client.get("/' + resource + '/" + item_id)',
                "    assert missing.status_code == 404",
                "",
                "",
            ]
        )

    if "get" in available_ops:
        lines.extend(
            [
                "async def test_get_unknown_returns_404(client: httpx.AsyncClient) -> None:",
                '    missing = await client.get("/' + resource + '/no-such-id")',
                "    assert missing.status_code == 404",
                "",
            ]
        )

    return "\n".join(lines) + "\n"

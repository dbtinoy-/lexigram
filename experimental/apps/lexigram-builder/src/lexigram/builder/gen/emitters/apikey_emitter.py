"""Emitters for the ``api_key_group`` node kind (nodes plan N4.2).

Screen-managed kind (Security modal) that graduates to real generation: the
first enabled group defines the emitted key family's header/prefix, and the
permission scopes of all enabled groups are unioned. Three artifacts:

* ``migrations/versions/b{n:04d}_api_keys.py`` — a chained alembic revision
  creating the ``api_keys`` table in the exact row shape ``APIKeyManager``
  reads (``id``, ``name``, ``key_hash``, ``prefix``, ``user_id``, ``scopes``
  JSON, ``expires_at``, ``revoked_at``, ``last_used_at``, ``last_used_ip``,
  ``created_at``, ``updated_at``).
* ``src/app/repositories/api_key_repository.py`` — a ``SqliteApiKeyRepository``
  implementing the framework's ``APIKeyRepositoryProtocol`` (``insert``,
  ``find_by_prefix``, ``find_by_user``, ``update_last_used``, ``revoke``)
  over the injected ``DatabaseProviderProtocol``.
* ``src/app/auth/api_keys.py`` — the group's constants (header, prefix,
  flattened ``resource:action`` scopes) plus ``build_authenticator`` and
  ``build_manager`` factories wiring the framework's
  ``APIKeyAuthenticator`` / ``APIKeyManager``.

The ``rate_limit`` and ``expires_at`` node knobs are reserved for v1.x:
parsed and validated but with no emission effect yet (documented here, in
TASKS.md, and in the emitted constants module).
"""

from __future__ import annotations

from lexigram.builder.gen.layout import DEFAULT_LAYOUT
from lexigram.builder.graph.models import ApiKeyGroupConfig

_HEADER = (
    "# Generated by lexigram-builder. Do not edit; regenerate instead.\n"
)


def _exec(sql: str, indent: str = "    ") -> str:
    return f"{indent}op.execute(\n{indent}    {sql!r}\n{indent})"


def merged_api_key_scopes(groups: list[ApiKeyGroupConfig]) -> list[str]:
    """Flatten permissions into ordered, de-duplicated ``resource:action``
    scope strings (explicit scopes appended verbatim after them)."""
    scopes: list[str] = []
    for group in groups:
        for perm in group.permissions:
            for action in perm.actions:
                scope = f"{perm.resource}:{action}"
                if scope not in scopes:
                    scopes.append(scope)
            for scope in perm.scopes:
                if scope not in scopes:
                    scopes.append(scope)
    return scopes


def emit_api_keys_migration(
    *,
    prev_revision: str | None,
    revision: str,
) -> str:
    """Render the alembic revision creating the ``api_keys`` table.

    Column set mirrors the payload ``APIKeyManager.create_key`` persists and
    the rows ``validate_key`` hydrates.
    """
    down_rev = repr(prev_revision) if prev_revision else "None"
    create_sql = (
        "CREATE TABLE IF NOT EXISTS api_keys (\n"
        '    "id" VARCHAR PRIMARY KEY NOT NULL,\n'
        '    "name" VARCHAR NOT NULL,\n'
        '    "key_hash" VARCHAR NOT NULL,\n'
        '    "prefix" VARCHAR NOT NULL,\n'
        '    "user_id" VARCHAR NOT NULL,\n'
        '    "scopes" TEXT,\n'
        '    "expires_at" VARCHAR,\n'
        '    "revoked_at" VARCHAR,\n'
        '    "last_used_at" VARCHAR,\n'
        '    "last_used_ip" VARCHAR,\n'
        '    "created_at" VARCHAR NOT NULL,\n'
        '    "updated_at" VARCHAR NOT NULL\n'
        ")"
    )
    prefix_index_sql = (
        'CREATE INDEX IF NOT EXISTS ix_api_keys_prefix ON api_keys ("prefix")'
    )
    user_index_sql = (
        'CREATE INDEX IF NOT EXISTS ix_api_keys_user_id ON api_keys ("user_id")'
    )

    lines: list[str] = [
        _HEADER.rstrip("\n"),
        '"""API-key store for the lexigram-auth API-key manager."""',
        "",
        "from __future__ import annotations",
        "",
        "from alembic import op",
        "",
        f"revision: str = {revision!r}",
        "down_revision: str | None = " + down_rev,
        "branch_labels = None",
        "depends_on = None",
        "",
        "",
        "def upgrade() -> None:",
        "    # Row shape matches APIKeyManager.create_key / validate_key.",
        _exec(create_sql),
        "    # validate_key pre-filters by display prefix.",
        _exec(prefix_index_sql),
        "    # list_keys filters by owner.",
        _exec(user_index_sql),
        "",
        "",
        "def downgrade() -> None:",
        "    op.execute('DROP INDEX IF EXISTS ix_api_keys_user_id')",
        "    op.execute('DROP INDEX IF EXISTS ix_api_keys_prefix')",
        "    op.execute('DROP TABLE IF EXISTS api_keys')",
        "",
    ]
    return "\n".join(lines)


def emit_api_key_repository() -> str:
    """Render ``src/app/repositories/api_key_repository.py``.

    Implements ``APIKeyRepositoryProtocol`` with the same provider-call
    pattern as the generated entity repositories (``execute_insert`` /
    ``execute_query``); scopes persist as JSON text, which the manager's
    ``_coerce_scopes`` reads back.
    """
    return "\n".join(
        [
            _HEADER,
            '"""SQLite-backed API-key repository (lexigram-auth contract).',
            "",
            "Implements ``APIKeyRepositoryProtocol`` for the framework's",
            "``APIKeyManager``: rows are plain dicts whose keys match the",
            "api_keys table columns; scopes persist as JSON text.",
            '"""',
            "from __future__ import annotations",
            "",
            "from datetime import datetime as _datetime",
            "from datetime import timezone as _timezone",
            "import json",
            "import uuid as _uuid",
            "from typing import Any",
            "",
            "from lexigram.contracts import DatabaseProviderProtocol",
            "",
            "",
            "def _now() -> str:",
            "    return _datetime.now(_timezone.utc).isoformat()",
            "",
            "",
            "class SqliteApiKeyRepository:",
            '    """API-key rows in the ``api_keys`` table.',
            "",
            "    Bound in the DI persistence provider and injected into",
            "    ``APIKeyManager`` (see app/auth/api_keys.py).",
            '    """',
            "",
            "    def __init__(self, provider: DatabaseProviderProtocol) -> None:",
            "        self._provider = provider",
            "",
            "    async def insert(self, payload: dict[str, Any]) -> str:",
            '        """Persist one key row; returns the generated key id."""',
            "        row = dict(payload)",
            '        row.setdefault("id", _uuid.uuid4().hex)',
            '        row.setdefault("created_at", _now())',
            '        row.setdefault("updated_at", _now())',
            '        scopes = row.get("scopes")',
            "        if not isinstance(scopes, str):",
            '            row["scopes"] = json.dumps(list(scopes or []))',
            '        revoked = row.get("revoked_at")',
            "        if revoked is not None and not isinstance(revoked, str):",
            '            row["revoked_at"] = revoked.isoformat()',
            '        expires = row.get("expires_at")',
            "        if expires is not None and not isinstance(expires, str):",
            '            row["expires_at"] = expires.isoformat()',
            '        await self._provider.execute_insert("api_keys", row)',
            '        return str(row["id"])',
            "",
            "    async def find_by_prefix(self, prefix: str) -> list[dict[str, Any]]:",
            '        """Active (non-revoked) keys sharing a display prefix."""',
            "        result = await self._provider.execute_query(",
            "            'SELECT * FROM api_keys'",
            '            " WHERE prefix = ? AND revoked_at IS NULL",',
            "            [prefix],",
            "        )",
            "        return [dict(row) for row in result]",
            "",
            "    async def find_by_user(self, user_id: str) -> list[dict[str, Any]]:",
            '        """Active (non-revoked) keys owned by *user_id*."""',
            "        result = await self._provider.execute_query(",
            "            'SELECT * FROM api_keys'",
            '            " WHERE user_id = ? AND revoked_at IS NULL",',
            "            [user_id],",
            "        )",
            "        return [dict(row) for row in result]",
            "",
            "    async def update_last_used(",
            "        self,",
            "        key_id: str,",
            "        ip_address: str | None,",
            "    ) -> None:",
            '        """Refresh last-used timestamp / IP after a validation."""',
            "        await self._provider.execute_update(",
            '            "api_keys",',
            "            {",
            '                "last_used_at": _now(),',
            '                "last_used_ip": ip_address,',
            '                "updated_at": _now(),',
            "            },",
            '            \'"id" = ?\',',
            "            [key_id],",
            "        )",
            "",
            "    async def revoke(self, key_id: str) -> bool:",
            '        """Mark a key revoked; True when a live key changed."""',
            "        result = await self._provider.execute_query(",
            "            'SELECT id FROM api_keys '",
            "            'WHERE id = ? AND revoked_at IS NULL',",
            "            [key_id],",
            "        )",
            "        rows = [dict(row) for row in result]",
            "        if not rows:",
            "            return False",
            "        await self._provider.execute_update(",
            '            "api_keys",',
            '            {"revoked_at": _now(), "updated_at": _now()},',
            '            \'"id" = ?\',',
            "            [key_id],",
            "        )",
            "        return True",
            "",
        ]
    )


def emit_api_keys_auth_module(
    config: ApiKeyGroupConfig,
    scopes: list[str],
    mods: dict[str, str] | None = None,
) -> str:
    """Render ``src/app/auth/api_keys.py`` for the first enabled group."""
    mods = mods or DEFAULT_LAYOUT.module_names()
    scope_lines = ",\n".join(f"    {s!r}" for s in scopes)
    lines: list[str] = [
        _HEADER,
        f'"""API-key family {config.key_prefix!r} (api-key-group node).',
        "",
        "Wires the framework's lexigram-auth API-key surface to this app:",
        "``API_KEY_SCOPES`` are the union of every enabled group's",
        "permissions (``resource:action`` pairs plus explicit scopes).",
        "The rate_limit and expires_at node knobs are reserved for v1.x",
        "and have no emission effect yet.",
        '"""',
        "from __future__ import annotations",
        "",
        "from collections.abc import Awaitable",
        "from typing import Any",
        "",
        "from lexigram.auth import APIKeyAuthenticator, APIKeyConfig",
        "from lexigram.auth.authn.apikeys import APIKeyManager",
        "from lexigram.contracts import DatabaseProviderProtocol",
        "from lexigram.contracts.auth import APIKeyRepositoryProtocol",
        "",
        (
            f"from {mods['repositories']}.api_key_repository import "
            "SqliteApiKeyRepository"
        ),
        "",
        "",
        "# HTTP header carrying the raw key.",
        f"API_KEY_HEADER: str = {config.key_header!r}",
        "# Key family prefix baked into generated raw keys.",
        f"API_KEY_PREFIX: str = {config.key_prefix!r}",
    ]
    if scopes:
        lines += [
            "# Scopes granted to this key family.",
            "API_KEY_SCOPES: tuple[str, ...] = (",
            scope_lines + ",",
            ")",
        ]
    else:
        lines += [
            "# No permissions configured on the group — empty scope set.",
            "API_KEY_SCOPES: tuple[str, ...] = ()",
        ]
    lines += [
        "",
        "",
        "def build_manager(",
        "    provider: DatabaseProviderProtocol,",
        ") -> APIKeyManager:",
        '    """APIKeyManager bound to this app\'s database provider."""',
        "    repo = SqliteApiKeyRepository(provider)",
        "    return APIKeyManager(repo)",
        "",
        "",
        "def build_authenticator(",
        "    lookup: dict[str, Any] | Awaitable[Any] | Any,",
        "    *,",
        '    query_param: str = "api_key",',
        ") -> APIKeyAuthenticator:",
        '    """Authenticator reading keys from API_KEY_HEADER.',
        "",
        "    ``lookup`` follows ``APIKeyConfig``: a dict of raw keys, or an",
        "    async/sync callable returning the key owner (``None`` rejects).",
        '    """',
        "    return APIKeyAuthenticator(",
        "        APIKeyConfig(",
        "            lookup=lookup,",
        "            header_name=API_KEY_HEADER,",
        "            query_param=query_param,",
        "        )",
        "    )",
        "",
    ]
    return "\n".join(lines)


"""Emitters for the ``audit_log`` node kind (nodes plan N4.1).

Two artifacts per wired entity:

* ``migrations/versions/b{n:04d}_{entity}_audit_log.py`` — a chained alembic
  revision creating the ``<table>_audit_log`` table (``id`` hex pk,
  ``entity_id``, ``op``, ``payload`` JSON text, ``created_at`` ISO timestamp)
  plus an ``entity_id`` lookup index.
* ``src/app/repositories/<entity>_audit_repository.py`` — an
  ``<Entity>AuditRepository`` (``record_created`` / ``record_updated`` /
  ``record_deleted`` / ``list_for``) that redacts excluded keys recursively
  and writes through the injected ``DatabaseProviderProtocol`` (the same
  ``execute_insert`` / ``execute_query`` pattern as the framework's generated
  repositories).

The ``capture_request_meta`` and ``retention_days`` node knobs are reserved
for v1.x: they are parsed and validated but have no emission effect yet
(documented in TASKS.md and the emitted repository docstring).
"""

from __future__ import annotations

from lexigram.builder.gen.emitters.context import pascal_entity, table_name
from lexigram.builder.graph.models import AuditLogConfig

_HEADER = (
    "# Generated by lexigram-builder. Do not edit; regenerate instead.\n"
)

_AUDIT_OPS: tuple[str, ...] = ("create", "update", "delete")


def _tuple_literal(values: tuple[str, ...]) -> str:
    """Render a tuple[str, ...] literal (empty -> ``()``)."""
    if not values:
        return "()"
    inner = ", ".join(repr(v) for v in values)
    return f"({inner},)"


def _exec(sql: str, indent: str = "    ") -> str:
    return f"{indent}op.execute(\n{indent}    {sql!r}\n{indent})"


def emit_audit_migration(
    entity_name: str,
    config: AuditLogConfig,
    *,
    prev_revision: str | None,
    revision: str,
) -> str:
    """Render the alembic revision creating ``<table>_audit_log``.

    ``prev_revision`` chains onto the last emitted migration (entity table,
    then any search/FTS revision) so the audit table lands last.
    """
    table = table_name(entity_name)
    audit_table = f"{table}_audit_log"
    down_rev = repr(prev_revision) if prev_revision else "None"
    ops = ", ".join(repr(op) for op in config.operations)
    create_sql = (
        f"CREATE TABLE IF NOT EXISTS {audit_table} (\n"
        '    "id" VARCHAR PRIMARY KEY NOT NULL,\n'
        '    "entity_id" VARCHAR NOT NULL,\n'
        '    "op" VARCHAR NOT NULL,\n'
        '    "payload" TEXT,\n'
        '    "created_at" VARCHAR NOT NULL\n'
        ")"
    )
    index_sql = (
        "CREATE INDEX IF NOT EXISTS ix_" + audit_table + "_entity_id "
        f'ON {audit_table} ("entity_id")'
    )

    lines: list[str] = [
        _HEADER.rstrip("\n"),
        f'"""Audit trail table for {table} (audit-log node)."""',
        "",
        "from __future__ import annotations",
        "",
        "from alembic import op",
        "",
        f"revision: str = {revision!r}",
        "down_revision: str | None = " + down_rev,
        "branch_labels = None",
        "depends_on = None",
        "",
        "",
        "def upgrade() -> None:",
        f"    # One row per audited mutation (ops: {ops}).",
        _exec(create_sql),
        "    # Latest-first trail lookups by entity id.",
        _exec(index_sql),
        "",
        "",
        "def downgrade() -> None:",
        f"    op.execute('DROP INDEX IF EXISTS ix_{audit_table}_entity_id')",
        f"    op.execute('DROP TABLE IF EXISTS {audit_table}')",
        "",
    ]
    return "\n".join(lines)


def emit_audit_repository(entity_name: str, config: AuditLogConfig) -> str:
    """Render ``src/app/repositories/<entity>_audit_repository.py``."""
    pascal = pascal_entity(entity_name)
    table = table_name(entity_name)
    audit_table = f"{table}_audit_log"
    ops = tuple(op for op in _AUDIT_OPS if op in config.operations)
    ops_note = ", ".join(ops) if ops else "none"
    capture_note = (
        "Captures only the configured payload keys."
        if config.capture_fields
        else "Captures the full payload minus the excluded keys."
    )

    # Redaction happens inside the repository (module-level constants) so the
    # controller hook stays a one-liner.
    excluded_literal = _tuple_literal(config.exclude_fields)
    captured_literal = _tuple_literal(config.capture_fields)

    return "\n".join(
        [
            _HEADER,
            f'"""{pascal} audit trail repository (audit-log node).',
            "",
            f"Records one row per audited mutation of {table} ({ops_note}).",
            capture_note,
            "The capture_request_meta and retention_days node knobs are",
            "reserved for v1.x and have no emission effect yet.",
            "",
            "Write/read pattern mirrors the framework's generated",
            "repositories: execute_insert for the audit row, execute_query",
            "for the trail listing.",
            '"""',
            "from __future__ import annotations",
            "",
            "from collections.abc import Mapping",
            "from datetime import datetime as _datetime",
            "from datetime import timezone as _timezone",
            "import json",
            "import uuid as _uuid",
            "from typing import Any",
            "",
            "from lexigram.contracts import DatabaseProviderProtocol",
            "",
            "",
            "# Keys redacted from persisted payloads (applied recursively).",
            f"_EXCLUDED_FIELDS: tuple[str, ...] = {excluded_literal}",
            "# When non-empty, only these payload keys are captured.",
            f"_CAPTURE_FIELDS: tuple[str, ...] = {captured_literal}",
            "",
            "",
            "def _redact(value: Any) -> Any:",
            '    """Slice captured keys / drop excluded keys, recursively."""',
            "    if isinstance(value, Mapping):",
            "        if _CAPTURE_FIELDS:",
            "            return {",
            "                key: value.get(key)",
            "                for key in _CAPTURE_FIELDS",
            "                if key in value",
            "            }",
            "        return {",
            "            key: _redact(item)",
            "            for key, item in value.items()",
            "            if key not in _EXCLUDED_FIELDS",
            "        }",
            "    if isinstance(value, list):",
            "        return [_redact(item) for item in value]",
            "    return value",
            "",
            "",
            f"class {pascal}AuditRepository:",
            f'    """Audit trail for the {table} table.',
            "",
            "    Injected into the entity's controller alongside its CRUD",
            "    repository; the controller records create/update/delete",
            "    mutations after they succeed.",
            '    """',
            "",
            "    def __init__(self, provider: DatabaseProviderProtocol) -> None:",
            "        self._provider = provider",
            "",
            "    async def record_created(",
            "        self,",
            "        entity_id: str,",
            "        payload: Mapping[str, Any] | None,",
            "    ) -> None:",
            '        """Record a create mutation."""',
            '        await self._record("create", entity_id, payload)',
            "",
            "    async def record_updated(",
            "        self,",
            "        entity_id: str,",
            "        payload: Mapping[str, Any] | None,",
            "    ) -> None:",
            '        """Record an update mutation."""',
            '        await self._record("update", entity_id, payload)',
            "",
            "    async def record_deleted(",
            "        self,",
            "        entity_id: str,",
            "    ) -> None:",
            '        """Record a delete mutation (payload is the removed id)."""',
            '        await self._record("delete", entity_id, None)',
            "",
            "    async def list_for(",
            "        self,",
            "        entity_id: str,",
            "        *,",
            "        limit: int = 50,",
            "    ) -> list[dict[str, Any]]:",
            '        """Latest-first audit rows for one entity."""',
            "        result = await self._provider.execute_query(",
            f"            'SELECT * FROM {audit_table} WHERE entity_id = ?'",
            '            " ORDER BY created_at DESC, id DESC LIMIT ?",',
            "            [entity_id, limit],",
            "        )",
            "        return [dict(row) for row in result]",
            "",
            "    async def _record(",
            "        self,",
            "        op: str,",
            "        entity_id: str,",
            "        payload: Mapping[str, Any] | None,",
            "    ) -> None:",
            '        """Persist one audit row (payload redacted + JSON-encoded)."""',
            "        row: dict[str, Any] = {",
            '            "id": _uuid.uuid4().hex,',
            '            "entity_id": entity_id,',
            '            "op": op,',
            '            "payload": (',
            "                json.dumps(_redact(dict(payload)))",
            "                if payload is not None",
            "                else None",
            "            ),",
            '            "created_at": _datetime.now(_timezone.utc).isoformat(),',
            "        }",
            f"        await self._provider.execute_insert({audit_table!r}, row)",
            "",
        ]
    )

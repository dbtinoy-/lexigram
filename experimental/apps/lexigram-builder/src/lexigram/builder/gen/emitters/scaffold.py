"""App-level scaffold emitter: everything not per-entity/per-route."""

from __future__ import annotations

from lexigram.builder.gen.emitters.context import pascal_entity, snake_case
from lexigram.builder.graph.models import EntityConfig, RouteConfig

GENERATED_HEADER = "# generated by lexigram-builder - do not edit\n"


def emit_scaffold_files(
    app_name: str,
    entities: list[EntityConfig],
    route_bindings: list[tuple[RouteConfig, EntityConfig]],
    *,
    relative_root: str,
) -> dict[str, str]:
    """Emit every non-entity/non-controller file of the generated project.

    Args:
        app_name: snake_case application name.
        entities: All entity configs.
        route_bindings: Route nodes with their bound entity.
        relative_root: Relative path from the generated pyproject back to
            this monorepo checkout root (e.g. ``../../..``).
    """
    app_pascal = pascal_entity(app_name)
    env_prefix = app_name.upper()
    controller_imports = "\n".join(
        f"from app.controllers.{snake_case(e.name)}_controller import "
        f"{pascal_entity(e.name)}Controller"
        for _r, e in route_bindings
    )
    controller_classes = ", ".join(
        f"{pascal_entity(e.name)}Controller" for _r, e in route_bindings
    )
    repo_imports = "\n".join(
        f"from app.repositories.{e.name}_repository import {pascal_entity(e.name)}Repository"
        for e in entities
    )
    repo_binds = "\n".join(
        f"        container.bind({pascal_entity(e.name)}Repository, {pascal_entity(e.name)}Repository(db_provider))"
        for e in entities
    )
    repo_exports = ", ".join(f"{pascal_entity(e.name)}Repository" for e in entities)

    return {
        "pyproject.toml": _pyproject(app_name, relative_root),
        "README.md": _readme(app_name, env_prefix),
        ".gitignore": _gitignore(),
        ".env.example": f"{env_prefix}_DATABASE_URL=sqlite:///{app_name}.db\n",
        "migrations/alembic.ini": _alembic_ini(env_prefix),
        "migrations/env.py": _alembic_env(env_prefix),
        "migrations/script.py.mako": _mako(),
        "src/app/__init__.py": GENERATED_HEADER,
        "src/app/config.py": _config(env_prefix, app_name),
        "src/app/main.py": _main(app_name, app_pascal),
        "src/app/module.py": _module(
            app_name,
            app_pascal,
            controller_imports,
            controller_classes,
            repo_exports,
        ),
        "src/app/di/__init__.py": GENERATED_HEADER,
        "src/app/di/provider.py": _persistence_provider(
            app_name, repo_imports, repo_binds, repo_exports
        ),
        "tests/conftest.py": GENERATED_HEADER,
    }



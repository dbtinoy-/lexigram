def _config(env_prefix: str, app_name: str) -> str:
    return f"""{GENERATED_HEADER}
from __future__ import annotations

import os

DATABASE_URL = os.getenv(
    "{env_prefix}_DATABASE_URL", "sqlite:///{app_name}.db"
)
HOST = os.getenv("{env_prefix}_HOST", "127.0.0.1")
PORT = int(os.getenv("{env_prefix}_PORT", "8000"))
"""


def _module(
    app_name: str,
    app_pascal: str,
    controller_imports: str,
    controller_classes: str,
    repo_exports: str,
) -> str:
    return f'''{GENERATED_HEADER}
from __future__ import annotations

from lexigram.di.module import DynamicModule, Module
from lexigram.di.module import module as module_decorator
from lexigram.sql.module import DatabaseModule
from lexigram.web.module import WebModule

from app.config import DATABASE_URL, HOST, PORT
from app.di.provider import PersistenceProvider
{controller_imports}


@module_decorator()
class {app_pascal}Module(Module):
    """Composition root for the generated application."""

    @classmethod
    def configure(cls) -> DynamicModule:
        return DynamicModule(
            module=cls,
            imports=[
                DatabaseModule.configure(config=DATABASE_URL),
                WebModule.configure(controllers=[{controller_classes}], host=HOST, port=PORT),
            ],
            providers=[PersistenceProvider],
            exports=[{repo_exports}],
        )
'''


def _main(app_name: str, app_pascal: str) -> str:
    return f'''{GENERATED_HEADER}
from __future__ import annotations

from lexigram.app.base import Application
from lexigram.web.server.runner import run_server_async

from app.module import {app_pascal}Module


def build_application() -> Application:
    app = Application(name="{app_name}")
    app.add_modules([{app_pascal}Module.configure()])
    return app


def main() -> None:
    """Boot the application and serve it until interrupted."""
    import asyncio

    app = build_application()

    async def _serve() -> None:
        await app.start()
        await run_server_async(app, host=app_host(), port=app_port())

    try:
        asyncio.run(_serve())
    except KeyboardInterrupt:
        pass


def app_host() -> str:
    from app.config import HOST

    return HOST


def app_port() -> int:
    from app.config import PORT

    return PORT


if __name__ == "__main__":
    main()
'''


def _persistence_provider(
    app_name: str,
    repo_imports: str,
    repo_binds: str,
    repo_exports: str,
) -> str:
    del app_name, repo_exports
    return f'''{GENERATED_HEADER}
from __future__ import annotations

from lexigram.contracts import DatabaseProviderProtocol
from lexigram.contracts.core.di import (
    BootContainerProtocol,
    ContainerRegistrarProtocol,
)
from lexigram.contracts.core.provider import ProviderPriority
from lexigram.di.provider import Provider

{repo_imports}


class PersistenceProvider(Provider):
    """Binds repositories to the resolved database provider."""

    def __init__(self) -> None:
        super().__init__(name="persistence", priority=ProviderPriority.INFRASTRUCTURE)

    async def register(self, container: ContainerRegistrarProtocol) -> None:
        pass

    async def boot(self, container: BootContainerProtocol) -> None:
        db_provider = await container.resolve(DatabaseProviderProtocol)
{repo_binds}
'''

"""A staging tree shaped like the project it is about to become (OQ-L5).

Framework generators are handed a directory and asked to write into it, and
what they write depends on where they think they are: ``GeneratorBase``
resolves a generated file's own package -- and its siblings' -- by walking up
from the output directory to the nearest ``[project]`` anchor.

Staging into ``.staging/models/`` told it nothing. The directory anchored to
no project, so ``_import_parts`` returned ``None``, every generated import
came out as a bare package name (``models``, not ``shop.models``), and the
writer repaired them afterwards against an import map the layout maintained
in parallel. Two descriptions of one fact, kept in agreement by a 136-cell
test -- which is a good tripwire and a bad design.

Staging into ``.staging/src/shop/modules/sales/models/``, under a stub
``pyproject.toml``, tells it the truth, and the kernel resolves
``shop.modules.sales.models`` on its own.

Two things fall out of shaping staging like the destination:

* **Files are keyed by destination, not by verb.** ``controller`` and
  ``resource`` stage into one directory and used to be walked twice, the
  second pass re-recording files under a verb nothing was credited to; a
  destination-keyed walk has no room for the collision.
* **The commit pass is one walk.** A staged file's path relative to the
  staging root *is* its project-relative destination, so committing is a
  copy with reconciliation, not a mapping exercise.
"""

from __future__ import annotations

from collections.abc import Iterator
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path

from lexigram.builder.gen.layout import WriterLayout
from lexigram.builder.gen.modular.placement import Placement
from lexigram.builder.gen.node_generators import dest_for

__all__ = ["StagedFile", "StagingArea"]

#: Minimal manifest making the staging root a project anchor. It exists to
#: be *found*, never to be built: ``find_project_anchor`` looks for a
#: ``[project]`` table and stops, so this is the whole contract.
_ANCHOR_MANIFEST = """\
# Generated by lexigram-builder for its staging tree. Not a real project.
#
# Framework generators resolve a generated module's own import path by
# walking up to the nearest [project] anchor. Without this file the staging
# tree anchors nowhere and every generated import degrades to a bare package
# name (OQ-L5). It is deleted with the rest of .staging after the run.
[project]
name = "lexigram-staging"
version = "0.0.0"
"""

_ANCHOR_FILENAME = "pyproject.toml"


def _verbs_by_component() -> dict[str, str]:
    """Component directory name -> the verb that writes it.

    Built from ``VERB_SPECS`` rather than declared, so it cannot drift; the
    first verb wins where two share a directory (``controller`` before
    ``resource``), which is the one whose reconciler is written for those
    files.
    """
    from lexigram.builder.gen.node_generators import VERB_SPECS

    by_component: dict[str, str] = {}
    for verb, spec in VERB_SPECS.items():
        component = spec.component or spec.default_output_dir.rsplit("/", 1)[-1]
        by_component.setdefault(component, verb)
    return by_component


@dataclass(frozen=True, slots=True)
class StagedFile:
    """One generator-produced file, with everything needed to commit it.

    Attributes:
        path: Absolute path in the staging tree.
        destination: Project-relative destination -- the staging path with
            the staging root removed, which is the whole point of shaping
            staging like the destination.
        verb: Generator verb that produced it.
        node_id: Node credited with it, or None for files nothing asked for.
        module: Bounded context that owns it, or None outside modular / for
            cross-cutting components.
    """

    path: Path
    destination: str
    verb: str
    node_id: str | None
    module: str | None


class StagingArea:
    """The staging tree for one writer run."""

    def __init__(
        self,
        root: Path,
        *,
        layout: WriterLayout,
        placement: Placement,
    ) -> None:
        self._root = root
        self._layout = layout
        self._placement = placement
        #: destination-relative path -> (verb, node_id, module)
        self._owners: dict[str, tuple[str, str | None, str | None]] = {}
        self._root.mkdir(parents=True, exist_ok=True)
        (self._root / _ANCHOR_FILENAME).write_text(
            _ANCHOR_MANIFEST, encoding="utf-8"
        )

    @property
    def root(self) -> Path:
        return self._root

    # ── directories ───────────────────────────────────────────────────

    def dir_for(self, verb: str, *, module: str | None = None) -> Path:
        """Staging directory for *verb*'s output, created.

        The path mirrors the destination exactly, so the generator writing
        into it sees the package it will actually live in.

        A module-local verb with no owning context has no correct
        destination, and guessing one produces a project that imports the
        wrong package and fails at boot, far from here -- so it raises,
        naming the verb, before anything is generated.
        """
        try:
            relative = dest_for(verb, self._layout, module=module)
        except ValueError as exc:
            raise ValueError(
                f"generator {verb!r} is module-local but no Module node "
                f"owns the node that asked for it. Assign that node to a "
                f"module, or its output has no correct destination."
            ) from exc
        directory = self._root / relative
        directory.mkdir(parents=True, exist_ok=True)
        return directory

    def module_for(self, node_id: str | None) -> str | None:
        """Bounded context that owns *node_id*'s output."""
        return self._placement.module_of(node_id)

    # ── running a generator ───────────────────────────────────────────

    @contextmanager
    def generating(
        self,
        verb: str,
        node_id: str | None,
        *,
        subdirectory_of: bool = False,
    ) -> Iterator[Path]:
        """Yield the directory for *verb*, crediting *node_id* with the output.

        Ownership is observed rather than declared: a framework generator
        names its own files, so the only reliable way to know what it wrote
        is to look before and after.

        Args:
            verb: Generator verb about to run.
            node_id: Node that asked for this output.
            subdirectory_of: When True the generator appends its own
                component directory (``resource`` writes
                ``<output_dir>/controllers/``), so it is handed the parent
                and the whole subtree is watched.
        """
        module = self.module_for(node_id)
        directory = self.dir_for(verb, module=module)
        watched = directory.parent if subdirectory_of else directory
        handed = watched
        before = self._snapshot(watched)
        try:
            yield handed
        finally:
            for path in self._snapshot(watched) - before:
                self._owners[self._relative(path)] = (verb, node_id, module)

    # ── committing ────────────────────────────────────────────────────

    def staged(self) -> list[StagedFile]:
        """Every staged file, in destination order.

        A file nobody was credited with still has to be committed -- it is
        the run's own scaffolding, not a mistake -- so it keeps the verb of
        the directory it landed in.
        """
        found: list[StagedFile] = []
        for path in sorted(self._root.rglob("*.py")):
            if not path.is_file():
                continue
            destination = self._relative(path)
            verb, node_id, module = self._owners.get(
                destination, (self._verb_for(destination), None, None)
            )
            found.append(
                StagedFile(
                    path=path,
                    destination=destination,
                    verb=verb,
                    node_id=node_id,
                    module=module,
                )
            )
        return found

    # ── internals ─────────────────────────────────────────────────────

    def _relative(self, path: Path) -> str:
        return path.relative_to(self._root).as_posix()

    @staticmethod
    def _snapshot(directory: Path) -> set[Path]:
        if not directory.exists():
            return set()
        return {p for p in directory.rglob("*.py") if p.is_file()}

    def _verb_for(self, destination: str) -> str:
        """Best-effort verb for an unattributed file, by its component.

        Only reachable when a generator wrote outside the directory it was
        handed. The verb decides reconciliation, so naming it by the
        component the file landed in beats treating the file as verbless --
        and under modular the component is the last path segment either
        way, module or shared.
        """
        directory = destination.rsplit("/", 1)[0] if "/" in destination else ""
        component = directory.rsplit("/", 1)[-1]
        return _verbs_by_component().get(component, "model")
